-- 1. Create bills table
CREATE TABLE IF NOT EXISTS public.bills (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    bill_no BIGINT GENERATED BY DEFAULT AS IDENTITY,
    custom_bill_no TEXT,
    bill_date DATE NOT NULL DEFAULT CURRENT_DATE,
    customer_name TEXT NOT NULL,
    customer_phone TEXT,
    customer_address TEXT,
    items JSONB NOT NULL DEFAULT '[]'::jsonb,
    subtotal NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    advance NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    total_amount NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    amount_in_words TEXT,
    payment_mode TEXT DEFAULT 'Cash',
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. Create company_settings table
CREATE TABLE IF NOT EXISTS public.company_settings (
    id TEXT PRIMARY KEY DEFAULT 'default',
    company_name TEXT NOT NULL DEFAULT 'Nagarathnamma',
    tagline TEXT NOT NULL DEFAULT 'SCREEN & OFFSET PRINTING',
    phone TEXT NOT NULL DEFAULT '9986073931',
    address TEXT NOT NULL DEFAULT '# 72, 4th Cross Road, Vidyaranyapura, Bengaluru – 560 097.',
    bank_name TEXT NOT NULL DEFAULT 'IDBI Bank',
    account_name TEXT NOT NULL DEFAULT 'K N NAGARATHNAMMA',
    account_no TEXT NOT NULL DEFAULT '0363104000056179',
    branch TEXT NOT NULL DEFAULT 'R.T. Nagar',
    ifsc_code TEXT NOT NULL DEFAULT 'IBKL0000363',
    next_bill_no BIGINT DEFAULT 1,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

