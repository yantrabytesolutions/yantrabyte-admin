-- 3. Enable Row Level Security (RLS) and allow public read/write for anon API
ALTER TABLE public.bills ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.company_settings ENABLE ROW LEVEL SECURITY;

-- Allow public access with anon key (so mobile & PC can sync without complex login)
CREATE POLICY "Allow public read bills" ON public.bills FOR SELECT USING (true);
CREATE POLICY "Allow public insert bills" ON public.bills FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update bills" ON public.bills FOR UPDATE USING (true);
CREATE POLICY "Allow public delete bills" ON public.bills FOR DELETE USING (true);

CREATE POLICY "Allow public read settings" ON public.company_settings FOR SELECT USING (true);
CREATE POLICY "Allow public update settings" ON public.company_settings FOR UPDATE USING (true);
CREATE POLICY "Allow public insert settings" ON public.company_settings FOR INSERT WITH CHECK (true);

-- 4. Enable Realtime Publications for instant sync across devices
ALTER PUBLICATION supabase_realtime ADD TABLE public.bills;
ALTER PUBLICATION supabase_realtime ADD TABLE public.company_settings;
